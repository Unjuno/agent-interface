"""Frozen, authority-neutral synthetic probe for Issue #4588.

No model is trained. The four transparent decision rules and synthetic labels
are fixed in this file before the deterministic corpus is generated.
"""
from __future__ import annotations

import json
import math
import random
from collections import Counter


SEED = 20260928
REPLICATES = 128
TAU = 1.0  # seconds; causal EWMA time constant for the smoothed arm
CLASSES = ("ACTION", "NO_OP", "YIELD")
ARMS = ("CURRENT_ONLY", "LEVEL_VELOCITY", "LEVEL_VELOCITY_ACCEL", "SMOOTHED")

# Values are confidence for one bounded candidate. Labels are independently
# specified synthetic decision targets, not generated by any tested arm.
SCENARIOS = (
    ("useful_convergence", (0.42, 0.60, 0.82), "ACTION", True),
    ("low_accelerating_correct", (0.20, 0.24, 0.31), "ACTION", True),
    ("velocity_alias_action", (0.40, 0.60, 0.80), "ACTION", True),
    ("velocity_alias_noop", (0.90, 0.85, 0.80), "NO_OP", True),
    # These two have identical current level and velocity, but different
    # second differences. Acceleration is the only permitted discriminator.
    ("accel_alias_action", (0.70, 0.70, 0.80), "ACTION", True),
    ("accel_alias_noop", (0.60, 0.70, 0.80), "NO_OP", True),
    ("plateau", (0.82, 0.82, 0.82), "NO_OP", True),
    ("high_confidence_decelerating", (0.94, 0.88, 0.82), "NO_OP", True),
    ("monotonic_divergence", (0.82, 0.60, 0.30), "YIELD", True),
    ("overshoot", (0.35, 0.93, 0.70), "YIELD", True),
    ("oscillation", (0.40, 0.90, 0.40), "YIELD", True),
    ("transient_spike", (0.30, 0.90, 0.40), "YIELD", True),
    ("low_flat_uncertain", (0.25, 0.26, 0.25), "YIELD", True),
    ("stale_history", (0.40, 0.60, 0.82), "YIELD", False),
    ("epoch_mismatch", (0.40, 0.60, 0.82), "YIELD", False),
    ("missing_sample", (None, 0.60, 0.82), "YIELD", False),
)


def features(samples: tuple[float, float, float], dts: tuple[float, float]):
    p0, p1, p2 = samples
    dt0, dt1 = dts
    v0 = (p1 - p0) / dt0
    v1 = (p2 - p1) / dt1
    acceleration = 2.0 * (v1 - v0) / (dt0 + dt1)
    return p2, v1, acceleration


def smooth(samples: tuple[float, float, float], dts: tuple[float, float]):
    """Causal time-aware EWMA; each output uses current/past values only."""
    p0, p1, p2 = samples
    dt0, dt1 = dts
    a0 = 1.0 - math.exp(-dt0 / TAU)
    a1 = 1.0 - math.exp(-dt1 / TAU)
    s0 = p0
    s1 = s0 + a0 * (p1 - s0)
    s2 = s1 + a1 * (p2 - s1)
    return s0, s1, s2


def decide(arm: str, samples, dts, valid: bool) -> str:
    if not valid or any(not isinstance(p, (float, int)) or not 0.0 <= p <= 1.0 for p in samples):
        return "YIELD"
    p = float(samples[-1])
    if arm == "CURRENT_ONLY":
        return "ACTION" if p >= 0.75 else "NO_OP" if p >= 0.45 else "YIELD"
    if arm == "SMOOTHED":
        samples = smooth(tuple(float(x) for x in samples), dts)
    p, velocity, acceleration = features(tuple(float(x) for x in samples), dts)
    # Opposite adjacent slopes represent oscillation/turning ambiguity.
    p0, p1, p2 = samples
    if (p1 - p0) * (p2 - p1) < -0.0025:
        return "YIELD"
    if arm == "LEVEL_VELOCITY":
        if p >= 0.75:
            return "ACTION" if velocity >= 0.05 else "NO_OP"
        if p < 0.40 and velocity >= 0.05:
            return "ACTION"
        return "NO_OP" if p >= 0.45 else "YIELD"
    if arm in ("LEVEL_VELOCITY_ACCEL", "SMOOTHED"):
        if p >= 0.75:
            if velocity >= 0.05 and acceleration >= 0.05:
                return "ACTION"
            return "NO_OP"
        if p < 0.40 and velocity >= 0.05 and acceleration >= 0.02:
            return "ACTION"
        return "NO_OP" if p >= 0.45 else "YIELD"
    raise ValueError(f"unknown arm: {arm}")


def make_corpus(noise: float):
    rng = random.Random(SEED + round(noise * 10000))
    rows = []
    for replicate in range(REPLICATES):
        # Every scenario at one replicate shares the same clock intervals and
        # confidence-noise vector. This preserves paired feature aliases.
        dts = (rng.uniform(0.75, 1.25), rng.uniform(0.75, 1.25))
        perturbations = tuple(rng.uniform(-noise, noise) for _ in range(3))
        for name, template, label, valid in SCENARIOS:
            observed = tuple(
                None if value is None else min(1.0, max(0.0, value + perturbations[index]))
                for index, value in enumerate(template)
            )
            rows.append({
                "scenario": name,
                "replicate": replicate,
                "truth": label,
                "valid": valid,
                "samples": observed,
                "dts": dts,
            })
    return rows


def paired_alias_controls(rows):
    lookup = {(row["scenario"], row["replicate"]): row for row in rows}
    result = {}
    pairs = {
        "velocity_alias": ("velocity_alias_action", "velocity_alias_noop"),
        "acceleration_alias": ("accel_alias_action", "accel_alias_noop"),
    }
    for pair_name, (left_name, right_name) in pairs.items():
        feature_equal = Counter()
        decision_equal = {arm: 0 for arm in ARMS}
        for replicate in range(REPLICATES):
            left = lookup[(left_name, replicate)]
            right = lookup[(right_name, replicate)]
            lf = features(tuple(float(x) for x in left["samples"]), left["dts"])
            rf = features(tuple(float(x) for x in right["samples"]), right["dts"])
            for dimension, (lv, rv) in zip(("level", "velocity", "acceleration"), zip(lf, rf)):
                if math.isclose(lv, rv, rel_tol=0.0, abs_tol=1e-12):
                    feature_equal[dimension] += 1
            for arm in ARMS:
                lp = decide(arm, left["samples"], left["dts"], left["valid"])
                rp = decide(arm, right["samples"], right["dts"], right["valid"])
                decision_equal[arm] += lp == rp
        result[pair_name] = {
            "replicates": REPLICATES,
            "feature_equal_replicates": dict(feature_equal),
            "decision_agreement_replicates": decision_equal,
        }
    return result


def score(rows):
    result = {}
    for arm in ARMS:
        confusion = Counter()
        for row in rows:
            predicted = decide(arm, row["samples"], row["dts"], row["valid"])
            confusion[(row["truth"], predicted)] += 1
        total = len(rows)
        non_action = sum(n for (truth, _), n in confusion.items() if truth != "ACTION")
        action_total = sum(n for (truth, _), n in confusion.items() if truth == "ACTION")
        noop_total = sum(n for (truth, _), n in confusion.items() if truth == "NO_OP")
        result[arm] = {
            "n": total,
            "correct": sum(n for (truth, pred), n in confusion.items() if truth == pred),
            "accuracy": sum(n for (truth, pred), n in confusion.items() if truth == pred) / total,
            "false_executable": sum(n for (truth, pred), n in confusion.items() if truth != "ACTION" and pred == "ACTION"),
            "false_executable_rate": sum(n for (truth, pred), n in confusion.items() if truth != "ACTION" and pred == "ACTION") / non_action,
            "missed_action": sum(n for (truth, pred), n in confusion.items() if truth == "ACTION" and pred != "ACTION"),
            "action_recall": sum(n for (truth, pred), n in confusion.items() if truth == "ACTION" and pred == "ACTION") / action_total,
            "false_noop_on_action": sum(n for (truth, pred), n in confusion.items() if truth == "ACTION" and pred == "NO_OP"),
            "correct_noop_rate": sum(n for (truth, pred), n in confusion.items() if truth == "NO_OP" and pred == "NO_OP") / noop_total,
            "unnecessary_actions": sum(n for (truth, pred), n in confusion.items() if truth != "ACTION" and pred == "ACTION"),
            "confusion": {f"{truth}->{pred}": n for (truth, pred), n in sorted(confusion.items())},
        }
    return result


def main():
    clean = make_corpus(0.0)
    mild = make_corpus(0.01)
    stress = make_corpus(0.12)
    # Contract controls: the acceleration alias is exactly indistinguishable
    # to level/velocity features and distinguishable by second difference.
    a = features((0.70, 0.70, 0.80), (1.0, 1.0))
    b = features((0.60, 0.70, 0.80), (1.0, 1.0))
    assert a[:2] == b[:2] and a[2] != b[2]
    for condition in (clean, mild, stress):
        lookup = {(row["scenario"], row["replicate"]): row for row in condition}
        for replicate in range(REPLICATES):
            velocity_left = lookup[("velocity_alias_action", replicate)]
            velocity_right = lookup[("velocity_alias_noop", replicate)]
            vf_left = features(tuple(velocity_left["samples"]), velocity_left["dts"])
            vf_right = features(tuple(velocity_right["samples"]), velocity_right["dts"])
            assert math.isclose(vf_left[0], vf_right[0], abs_tol=1e-12)
            assert not math.isclose(vf_left[1], vf_right[1], abs_tol=1e-8)
            acceleration_left = lookup[("accel_alias_action", replicate)]
            acceleration_right = lookup[("accel_alias_noop", replicate)]
            af_left = features(tuple(acceleration_left["samples"]), acceleration_left["dts"])
            af_right = features(tuple(acceleration_right["samples"]), acceleration_right["dts"])
            assert math.isclose(af_left[0], af_right[0], abs_tol=1e-12)
            assert math.isclose(af_left[1], af_right[1], abs_tol=1e-12)
            assert not math.isclose(af_left[2], af_right[2], abs_tol=1e-8)
    # Altering only the future/current third sample cannot alter EWMA prefix.
    assert smooth((0.4, 0.6, 0.8), (1.0, 1.0))[:2] == smooth((0.4, 0.6, 0.7), (1.0, 1.0))[:2]
    # Invalid history always fails closed for every feature arm.
    for arm in ARMS:
        assert decide(arm, (None, 0.6, 0.82), (1.0, 1.0), False) == "YIELD"
        assert decide(arm, ("malformed", 0.6, 0.82), (1.0, 1.0), True) == "YIELD"
    output = {
        "schema": "issue4588_synthetic_confidence_trajectory_probe_v2",
        "seed": SEED,
        "replicates_per_scenario": REPLICATES,
        "scenario_count": len(SCENARIOS),
        "noise_bounds": {"clean": 0.0, "mild": 0.01, "stress": 0.12},
        "rules_frozen_in_source": True,
        "model_trained": False,
        "authority_granted": False,
        "contract_controls": "PASS",
        "paired_alias_controls": {
            "clean": paired_alias_controls(clean),
            "mild_noise": paired_alias_controls(mild),
            "stress_noise": paired_alias_controls(stress),
        },
        "metrics": {
            "clean": score(clean),
            "mild_noise": score(mild),
            "stress_noise": score(stress),
        },
    }
    print(json.dumps(output, sort_keys=True, separators=(",", ":")))


if __name__ == "__main__":
    main()
